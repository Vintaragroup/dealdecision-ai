/**
 * debug-carmoola-g3.ts
 *
 * Diagnose why the stored investor-insights report for Carmoola shows
 *   "G3 Fail: GATE_STRUCTURED_JSON_UNREADABLE"
 * even though the current gates.ts no longer produces that reason code
 * and the actual structured_json data passes the current schema.
 *
 * Deal : da96b5a9-e5b2-46c1-a6ef-da037f876426
 *
 * Usage (from apps/worker/):
 *   node -r ./src/bin/load-env.cjs tmp/debug-carmoola-g3.cjs
 *
 * Outputs:
 *   1. Stored G3 result from investor_insight_reports
 *   2. All visual_extractions rows for the deal (structured_json summary)
 *   3. Whether each row passes/fails the current StructuredJsonMinimalSchema
 *   4. Net verdict: "Would G3 pass today?" (Yes / No + reason)
 */
import { Pool } from "pg";
import { z } from "zod";
import * as fs from "node:fs";
import * as path from "node:path";

const DEAL_ID = "da96b5a9-e5b2-46c1-a6ef-da037f876426";

// ── Mirror of current StructuredJsonMinimalSchema from gates.ts ──────────────
const StructuredJsonMinimalSchema = z
  .record(z.unknown())
  .refine((obj) => Object.keys(obj).length > 0, { message: "empty object" });

// ── DB setup ──────────────────────────────────────────────────────────────────

const cs = process.env.DATABASE_URL;
if (!cs) { console.error("DATABASE_URL not set"); process.exit(1); }

const pool = new Pool({
  connectionString: cs,
  ssl: cs.includes("sslmode=require") || process.env.PGSSLMODE === "require"
    ? { rejectUnauthorized: false }
    : false,
});

// ── Main ──────────────────────────────────────────────────────────────────────

async function main() {
  console.log("=== debug-carmoola-g3 ===");
  console.log(`Deal ID : ${DEAL_ID}\n`);

  // ── 1. Current stored G3 result ────────────────────────────────────────────
  console.log("=== 1. STORED INVESTOR INSIGHTS GATE STATE ===\n");
  const repRes = await pool.query<{
    render_package: Record<string, unknown>;
    updated_at: string;
  }>(
    `SELECT render_package, updated_at
       FROM public.investor_insight_reports
      WHERE deal_id = $1::uuid
      ORDER BY updated_at DESC
      LIMIT 1`,
    [DEAL_ID]
  );

  if (!repRes.rows.length) {
    console.log("No stored report found for Carmoola.");
  } else {
    const rp = repRes.rows[0].render_package;
    console.log(`Report updated_at : ${repRes.rows[0].updated_at}`);

    // Find gate_state section
    const sections = (rp?.sections ?? []) as Array<{ key: string; items?: unknown[]; body?: string }>;
    const gateSection = sections.find((s) => s.key === "gate_state");
    if (gateSection?.items) {
      const g3 = (gateSection.items as Array<{ gate: string; [k: string]: unknown }>)
        .find((r) => r.gate === "G3");
      if (g3) {
        console.log("Stored G3 result:", JSON.stringify(g3, null, 2));
        if (g3.reason_code === "GATE_STRUCTURED_JSON_UNREADABLE") {
          console.log(
            "\n⚠  ORPHANED REASON CODE: GATE_STRUCTURED_JSON_UNREADABLE was removed in the\n" +
            "   initial refactor commit.  This report was generated by the PR1 v0 build.\n" +
            "   Re-running the job will use current code and should produce G3=Pass.\n"
          );
        }
      } else {
        console.log("G3 result not found in stored gate_state.  Keys:", sections.map((s) => s.key));
      }
    } else {
      console.log("gate_state section not found. render_package keys:", Object.keys(rp ?? {}));
    }
  }

  // ── 2. All visual_extractions rows for the deal ────────────────────────────
  console.log("\n=== 2. VISUAL_EXTRACTIONS ROWS (structured_json) ===\n");
  const veRes = await pool.query<{
    ve_id: string;
    va_id: string;
    doc_id: string;
    raw_json: string | null;
  }>(
    `SELECT
       ve.id AS ve_id,
       va.id AS va_id,
       d.id  AS doc_id,
       ve.structured_json::text AS raw_json
       FROM public.visual_extractions ve
       JOIN public.visual_assets va ON va.id = ve.visual_asset_id
       JOIN public.documents d ON d.id = va.document_id
      WHERE d.deal_id = $1::uuid
        AND ve.structured_json IS NOT NULL
      ORDER BY d.id, va.id`,
    [DEAL_ID]
  );

  console.log(`Total rows with non-NULL structured_json : ${veRes.rows.length}`);

  if (veRes.rows.length === 0) {
    console.log("No rows! G3 would fail GATE_STRUCTURED_JSON_MISSING with current code.");
    return;
  }

  // ── 3. Schema check each row ───────────────────────────────────────────────
  const rawDump: string[] = [];
  let passCount = 0;
  let failCount = 0;

  for (const [i, row] of veRes.rows.entries()) {
    const byteLen = row.raw_json?.length ?? 0;
    let verdict: string;
    let parseResult: "ok" | "error" = "ok";
    let schemaPassed = false;

    try {
      const parsed = JSON.parse(row.raw_json!);
      const sr = StructuredJsonMinimalSchema.safeParse(parsed);
      schemaPassed = sr.success;
      verdict = sr.success ? "PASS" : `FAIL(SCHEMA_MISMATCH: ${sr.error.message})`;
    } catch (e: unknown) {
      parseResult = "error";
      verdict = `FAIL(PARSE_ERROR: ${e instanceof Error ? e.message : String(e)})`;
    }

    if (parseResult === "ok" && schemaPassed) passCount++;
    else failCount++;

    const preview = (row.raw_json ?? "").slice(0, 120);
    const keys = parseResult === "ok"
      ? Object.keys(JSON.parse(row.raw_json!)).join(", ")
      : "(parse error)";

    console.log(`Row ${i + 1}: ve_id=${row.ve_id.slice(0, 8)} bytes=${byteLen} verdict=${verdict}`);
    console.log(`         keys=[${keys}]`);
    console.log(`         preview: ${preview}\n`);

    rawDump.push(`--- Row ${i + 1}: ve_id=${row.ve_id} ---\n${row.raw_json}\n`);
  }

  console.log(`Schema check summary: ${passCount} pass / ${failCount} fail`);

  // ── 4. Net verdict ─────────────────────────────────────────────────────────
  console.log("\n=== 3. NET VERDICT ===\n");
  if (passCount > 0) {
    console.log("✅  G3 would PASS today: at least one non-empty structured_json object found.");
    console.log("   Action: re-run investor-insights job for Carmoola.");
    console.log(`   Command: pnpm --filter worker repair:insight-slots -- --deal-id ${DEAL_ID}`);
  } else if (veRes.rows.length > 0 && failCount > 0) {
    console.log("❌  G3 would still FAIL: all rows fail parse or schema check.");
    console.log("   Investigate the previews above.");
  } else {
    console.log("❌  G3 would FAIL (MISSING): no rows with non-NULL structured_json.");
  }

  // ── 5. Write raw dump ──────────────────────────────────────────────────────
  const tmpDir = path.join(process.cwd(), "tmp");
  if (!fs.existsSync(tmpDir)) fs.mkdirSync(tmpDir, { recursive: true });
  const dumpPath = path.join(tmpDir, "carmoola-structured-json.raw.txt");
  fs.writeFileSync(dumpPath, rawDump.join("\n"), "utf-8");
  console.log(`\nRaw dump written to : ${dumpPath}`);
}

main()
  .catch((err) => { console.error(err); process.exit(1); })
  .finally(() => pool.end());

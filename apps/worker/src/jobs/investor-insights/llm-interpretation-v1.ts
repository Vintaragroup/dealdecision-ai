// ─── Types ────────────────────────────────────────────────────────────────────

/**
 * Investment posture:
 *  - GO:          Multiple supporting signals; compelling fundamentals
 *  - INVESTIGATE: Interesting but requires diligence; gaps or risks present
 *  - CAUTION:     Notable red flags or significant data gaps
 *  - PASS:        Clear negatives, missing fundamentals, or fatal flaws
 */
export type LlmInterpretationPosture = "GO" | "INVESTIGATE" | "CAUTION" | "PASS";

/**
 * Confidence in the posture classification:
 *  - HIGH:   ≥2 cross-validated signals with no major gaps
 *  - MEDIUM: Some signals present but gaps remain
 *  - LOW:    Sparse data, major contradictions, or heavy reliance on incomplete evidence
 */
export type LlmInterpretationConfidence = "HIGH" | "MEDIUM" | "LOW";

/** All valid posture values for exhaustive validation checks. */
export const POSTURE_VALUES: ReadonlySet<string> = new Set<LlmInterpretationPosture>([
	"GO",
	"INVESTIGATE",
	"CAUTION",
	"PASS",
]);

/** All valid confidence values for exhaustive validation checks. */
export const CONFIDENCE_VALUES: ReadonlySet<string> = new Set<LlmInterpretationConfidence>([
	"HIGH",
	"MEDIUM",
	"LOW",
]);

export interface LlmInterpretationV1 {
	schema_version: "llm_interpretation_v1";
	/** Investment posture classification: GO | INVESTIGATE | CAUTION | PASS */
	posture: LlmInterpretationPosture;
	/** Confidence level: HIGH | MEDIUM | LOW */
	confidence: LlmInterpretationConfidence;
	/** 2–4 sentence executive interpretation of the investment opportunity. */
	executive_summary: string;
	/** Up to 3 key strengths grounded in extracted evidence. Each ≤150 chars. */
	strengths: string[];
	/** Up to 3 key risks or concerns. Each ≤150 chars. */
	risks: string[];
	/** Up to 3 targeted questions for the next investor-company interaction. Each ≤180 chars. */
	next_questions: string[];
	/**
	 * 1–3 sentences on the financial profile:
	 * revenue trajectory, growth rate, margins, burn, runway, stage-readiness.
	 * Use "Not disclosed" when financial data is absent.
	 */
	financial_outlook: string;
	/**
	 * 1–3 sentences on business quality:
	 * model defensibility, team signals, operational maturity, product-market fit evidence.
	 */
	business_quality: string;
	/**
	 * 1–3 sentences on market position:
	 * TAM/SAM/SOM claims, competitive positioning, and whether the sizing is credible.
	 */
	market_position: string;
	/**
	 * 1–3 sentences interpreting the raise:
	 * amount, structure / instrument, valuation, use of funds, and how they relate.
	 */
	capital_and_raise_interpretation: string;
	/**
	 * 1–3 sentences on product differentiation:
	 * what the company actually builds, what makes it potentially unique,
	 * and what extracted evidence supports that claim.
	 * Use "Not determinable from available signals" when product data is absent.
	 */
	product_differentiation: string;
	/**
	 * 1–3 sentences on go-to-market strategy:
	 * target buyer, pricing signals, distribution channels, and commercial model.
	 * Use "Not determinable from available signals" when GTM data is absent.
	 */
	go_to_market_strategy: string;
	/**
	 * PR36: 1–3 sentences on the external macro + sector environment:
	 * industry growth signals, macro tailwinds/headwinds, and sector competitiveness
	 * derived from external due diligence market research.
	 * Empty string when external diligence is unavailable.
	 */
	external_market_context: string;
	/**
	 * PR36: 1–3 sentences mapping the competitive landscape:
	 * comparable companies identified via web research, market structure,
	 * and whether the company's differentiation claims hold up externally.
	 * Empty string when external diligence is unavailable.
	 */
	competitive_landscape: string;
	/**
	 * PR36: 1–3 sentences on claim verification:
	 * classifies deck claims as supported / contradicted / mixed / insufficient evidence
	 * based on claim_corroborations from external due diligence.
	 * Empty string when external diligence is unavailable.
	 */
	claim_verification_summary: string;
	/**
	 * PR36: 1–3 sentences on externally-sourced risk signals:
	 * regulatory risks, reputation signals, sector instability, or negative news
	 * surfaced via external_risks and company_footprint buckets.
	 * Empty string when external diligence is unavailable.
	 */
	external_risk_signals: string;
	/**
	 * Up to 3 critical unknowns that must be answered before conviction is possible.
	 * Each ≤150 chars.
	 */
	key_unknowns: string[];
	/**
	 * When non-null, warns the reader that evidence coverage was limited at
	 * time of generation and the interpretation may be incomplete.
	 */
	evidence_caveat: string | null;
	/** True when numeric-parity validation passed. */
	validated: boolean;
}

export interface LlmInterpretationArgs {
	canonicalFieldsBody: string | null;
	insightSlotsBody: string | null;
	financialStmtBody: string | null;
	useOfFundsBody: string | null;
	conflictsBody: string | null;
	/** Derived financial health metrics (revenue, growth, margins, efficiency). */
	financialHealthBody: string | null;
	/** Deterministic financial reconciliation summary. */
	financialReconciliationBody: string | null;
	/** Deck-derived financial signal mentions (ARR, MRR, burn, revenue, pricing, unit econ). */
	deckFinancialSignalsBody: string | null;
	/**
	 * Deterministic product signal bundle: capability language, automation/AI mentions,
	 * workflow integrations, competitive slide text, and differentiation claims.
	 */
	productSignalsBundleBody: string | null;
	/**
	 * Deterministic GTM signal bundle: pricing structures, target customer/ICP descriptions,
	 * subscription tiers, distribution/partnership signals, GTM-related use-of-funds.
	 */
	gtmSignalsBundleBody: string | null;
	/**
	 * PR35: Serialised external due diligence body (from Tavily web research).
	 * LLM-safe — contains only sanitised snippets and claim corroborations.
	 * Null when Tavily is disabled or no results were found.
	 */
	externalDiligenceBody: string | null;
	dealName?: string;
	productNarrativeBody?: string | null;
	/**
	 * When true the LLM is instructed to include an evidence caveat in its
	 * output, and the caller passes through the coverage metrics for context.
	 */
	evidenceCaveat?: boolean;
}

export type LlmInterpretationResult =
	| { ok: true; value: LlmInterpretationV1 }
	| { ok: false; reason: string; unknownTokens?: string[] };


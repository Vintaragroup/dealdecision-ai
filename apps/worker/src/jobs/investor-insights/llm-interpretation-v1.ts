// ─── LLM caller ───────────────────────────────────────────────────────────────

/**
 * Call gpt-4o-mini to generate an investment interpretation from canonical inputs.
 * Validates output has no hallucinated numbers before returning.
 */
export async function generateLlmInterpretationV1(
	args: LlmInterpretationArgs
): Promise<LlmInterpretationResult> {
	// Build canonical corpus for validation and LLM context.
	// Ordering is deliberate: identity first, then business context, then financials,
	// then evidence quality markers.
	const parts: string[] = [];
	if (args.dealName) parts.push(`## Deal Identity\nDeal name: ${args.dealName}`);
	if (args.productNarrativeBody) parts.push(`## Product Narrative\n${args.productNarrativeBody}`);
	if (args.canonicalFieldsBody) parts.push(`## Canonical Fields\n${args.canonicalFieldsBody}`);
	if (args.insightSlotsBody) parts.push(`## Insight Slots (Raise / Market / Traction / Valuation / Use-of-Funds)\n${args.insightSlotsBody}`);
	if (args.financialHealthBody) parts.push(`## Financial Health Metrics\n${args.financialHealthBody}`);
	if (args.financialStmtBody) parts.push(`## Financial Statement (XLSX)\n${args.financialStmtBody}`);
	if (args.financialReconciliationBody) parts.push(`## Financial Reconciliation\n${args.financialReconciliationBody}`);
	if (args.deckFinancialSignalsBody) parts.push(`## Deck Financial Signals (PDF/PPT)\n${args.deckFinancialSignalsBody}`);
	if (args.productSignalsBundleBody) parts.push(`## Product & Differentiation Signals\n${args.productSignalsBundleBody}`);
	if (args.gtmSignalsBundleBody) parts.push(`## Go-To-Market Signals\n${args.gtmSignalsBundleBody}`);
	if (args.useOfFundsBody) parts.push(`## Use of Funds Detail\n${args.useOfFundsBody}`);
	if (args.conflictsBody) parts.push(`## Conflicting Fields (detected)\n${args.conflictsBody}`);
	if (args.externalDiligenceBody) parts.push(`## External Due Diligence (web research)\n${args.externalDiligenceBody}`);

	if (parts.length === 0) {
		return { ok: false, reason: "no_canonical_data" };
	}

	const canonicalCorpus = parts.join("\n\n");

	const apiKey = process.env.OPENAI_API_KEY;
	if (!apiKey) {
		return { ok: false, reason: "missing_openai_api_key" };
	}

	const providerConfig: ProviderConfig = {
		type: "openai",
		enabled: true,
		priority: 1,
		apiKey,
		timeout: 30_000,
		retries: 2,
	};

	const provider = new OpenAIGPT4oProvider(providerConfig);
	const systemPrompt = args.evidenceCaveat ? SYSTEM_PROMPT_WITH_CAVEAT : SYSTEM_PROMPT_BASE;

	let response: Awaited<ReturnType<typeof provider.complete>>;
	try {
		response = await provider.complete({
			task: "synthesis",
			model: "gpt-4o-mini" as never,
			temperature: 0,
		max_tokens: 2200,
			messages: [
				{ role: "system", content: systemPrompt },
				{ role: "user", content: canonicalCorpus },
			],
			metadata: { kind: "llm_interpretation_v1" },
		});
	} catch {
		return { ok: false, reason: "llm_call_failed" };
	}

	if (!response?.content) {
		return { ok: false, reason: "llm_empty_response" };
	}

	// Parse JSON output
	let parsed: unknown;
	try {
		parsed = JSON.parse(response.content.trim());
	} catch {
		const jsonMatch = /\{[\s\S]*\}/.exec(response.content);
		if (!jsonMatch) {
			return { ok: false, reason: "llm_output_not_json" };
		}
		try {
			parsed = JSON.parse(jsonMatch[0]);
		} catch {
			return { ok: false, reason: "llm_output_not_json" };
		}
	}

	if (
		!parsed ||
		typeof parsed !== "object" ||
		Array.isArray(parsed)
	) {
		return { ok: false, reason: "llm_output_schema_mismatch" };
	}

	const raw = parsed as Record<string, unknown>;

	// Validate posture
	if (typeof raw["posture"] !== "string" || !POSTURE_VALUES.has(raw["posture"])) {
		return { ok: false, reason: "llm_output_invalid_posture" };
	}

	// Validate confidence
	if (typeof raw["confidence"] !== "string" || !CONFIDENCE_VALUES.has(raw["confidence"])) {
		return { ok: false, reason: "llm_output_invalid_confidence" };
	}
	const confidence = raw["confidence"] as LlmInterpretationConfidence;

	// Validate required string fields
	const requiredStrings = [
		"executive_summary",
		"product_differentiation",
		"go_to_market_strategy",
		"financial_outlook",
		"business_quality",
		"market_position",
		"capital_and_raise_interpretation",
	];
	for (const field of requiredStrings) {
		if (typeof raw[field] !== "string") {
			return { ok: false, reason: "llm_output_schema_mismatch" };
		}
	}
	// PR36: external intelligence fields — optional, default to empty string
	const external_market_context = typeof raw["external_market_context"] === "string"
		? (raw["external_market_context"] as string).trim() : "";
	const competitive_landscape = typeof raw["competitive_landscape"] === "string"
		? (raw["competitive_landscape"] as string).trim() : "";
	const claim_verification_summary = typeof raw["claim_verification_summary"] === "string"
		? (raw["claim_verification_summary"] as string).trim() : "";
	const external_risk_signals = typeof raw["external_risk_signals"] === "string"
		? (raw["external_risk_signals"] as string).trim() : "";
	if (
		!Array.isArray(raw["strengths"]) ||
		!Array.isArray(raw["risks"]) ||
		!Array.isArray(raw["next_questions"]) ||
		!Array.isArray(raw["key_unknowns"])
	) {
		return { ok: false, reason: "llm_output_schema_mismatch" };
	}

	const toStringArray = (arr: unknown[], maxItems: number, maxChars: number): string[] =>
		arr
			.filter((x): x is string => typeof x === "string" && x.trim().length > 0)
			.slice(0, maxItems)
			.map((s) => s.trim().slice(0, maxChars));

	const executive_summary = (raw["executive_summary"] as string).trim();
	const product_differentiation = (raw["product_differentiation"] as string).trim();
	const go_to_market_strategy = (raw["go_to_market_strategy"] as string).trim();
	const financial_outlook = (raw["financial_outlook"] as string).trim();
	const business_quality = (raw["business_quality"] as string).trim();
	const market_position = (raw["market_position"] as string).trim();
	const capital_and_raise_interpretation = (raw["capital_and_raise_interpretation"] as string).trim();
	const strengths = toStringArray(raw["strengths"] as unknown[], 3, 150);
	const risks = toStringArray(raw["risks"] as unknown[], 3, 150);
	const next_questions = toStringArray(raw["next_questions"] as unknown[], 3, 180);
	const key_unknowns = toStringArray(raw["key_unknowns"] as unknown[], 3, 150);

	// Numeric-parity validation — covers ALL text fields including PR36 external fields
	const allOutputText = [
		executive_summary,
		product_differentiation,
		go_to_market_strategy,
		financial_outlook,
		business_quality,
		market_position,
		capital_and_raise_interpretation,
		external_market_context,
		competitive_landscape,
		claim_verification_summary,
		external_risk_signals,
		...strengths,
		...risks,
		...next_questions,
		...key_unknowns,
	].join(" ");
	const fullOutput = normalizeLlmFinanceShorthand(allOutputText);
	const { ok: parityOk, unknown: unknownTokens } = validateNoNewNumbers(fullOutput, canonicalCorpus);

	if (!parityOk) {
		return { ok: false, reason: "numeric_parity_failed", unknownTokens };
	}

	const evidenceCaveat: string | null = args.evidenceCaveat
		? "Limited coverage — interpretation may be incomplete"
		: null;

	return {
		ok: true,
		value: {
			schema_version: "llm_interpretation_v1",
			posture: raw["posture"] as LlmInterpretationPosture,
			confidence,
			executive_summary,
			product_differentiation,
			go_to_market_strategy,
			financial_outlook,
			business_quality,
			market_position,
			capital_and_raise_interpretation,
			external_market_context,
			competitive_landscape,
			claim_verification_summary,
			external_risk_signals,
			strengths,
			risks,
			next_questions,
			key_unknowns,
			evidence_caveat: evidenceCaveat,
			validated: true,
		},
	};
}

// ─── Section body serializer ──────────────────────────────────────────────────

/**
 * Serialize a LlmInterpretationV1 to a human-readable body string suitable for
 * the render_package section body field.
 *
 * The JSON representation is embedded under a delimiter so that the UI can
 * parse structured data without a separate field.
 */
export function serializeLlmInterpretationBody(value: LlmInterpretationV1): string {
	const lines: string[] = [];

	// Posture + confidence header
	lines.push(`Investment Posture: ${value.posture} | Confidence: ${value.confidence}`);

	if (value.evidence_caveat) {
		lines.push(`⚠ ${value.evidence_caveat}`);
	}
	lines.push("");

	lines.push("Executive Summary");
	lines.push(value.executive_summary);
	lines.push("");

	lines.push("Financial Outlook");
	lines.push(value.financial_outlook);
	lines.push("");

	lines.push("Business Quality");
	lines.push(value.business_quality);
	lines.push("");

	lines.push("Market Position");
	lines.push(value.market_position);
	lines.push("");

	lines.push("Capital & Raise");
	lines.push(value.capital_and_raise_interpretation);
	lines.push("");

	lines.push("Product & Differentiation");
	lines.push(value.product_differentiation);
	lines.push("");

	lines.push("Go-To-Market Strategy");
	lines.push(value.go_to_market_strategy);
	lines.push("");

	if (value.external_market_context) {
		lines.push("External Market Context");
		lines.push(value.external_market_context);
		lines.push("");
	}

	if (value.competitive_landscape) {
		lines.push("Competitive Landscape");
		lines.push(value.competitive_landscape);
		lines.push("");
	}

	if (value.claim_verification_summary) {
		lines.push("Claim Verification");
		lines.push(value.claim_verification_summary);
		lines.push("");
	}

	if (value.external_risk_signals) {
		lines.push("External Risk Signals");
		lines.push(value.external_risk_signals);
		lines.push("");
	}

	if (value.strengths.length > 0) {
		lines.push("Strengths");
		value.strengths.forEach((s) => lines.push(`• ${s}`));
		lines.push("");
	}

	if (value.risks.length > 0) {
		lines.push("Risks");
		value.risks.forEach((r) => lines.push(`• ${r}`));
		lines.push("");
	}

	if (value.next_questions.length > 0) {
		lines.push("Next Questions");
		value.next_questions.forEach((q) => lines.push(`• ${q}`));
		lines.push("");
	}

	if (value.key_unknowns.length > 0) {
		lines.push("Key Unknowns");
		value.key_unknowns.forEach((u) => lines.push(`• ${u}`));
		lines.push("");
	}

	// Embed structured JSON for UI parsing
	lines.push(`---llm_interpretation_v1_json---`);
	lines.push(JSON.stringify(value));

	return lines.join("\n");
}

/**
 * Parse a LlmInterpretationV1 from a section body string previously created
 * by serializeLlmInterpretationBody. Returns null on parse failure.
 */
export function parseLlmInterpretationBody(body: string): LlmInterpretationV1 | null {
	const delimiter = "---llm_interpretation_v1_json---\n";
	const idx = body.indexOf(delimiter);
	if (idx === -1) return null;
	try {
		const json = body.slice(idx + delimiter.length).trim();
		const parsed = JSON.parse(json) as LlmInterpretationV1;
		if (parsed?.schema_version !== "llm_interpretation_v1") return null;
		return parsed;
	} catch {
		return null;
	}
}
